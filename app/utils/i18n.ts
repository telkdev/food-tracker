export const messages: Record<Locale, Record<MsgKey, string>> = { en, ru }

/** ru/uk/be → ru, everything else → en. Accepts a navigator.language or an Accept-Language header. */
export function pickLocale(lang: string | null | undefined): Locale {
  const first = (lang || '').split(',')[0]!.trim().toLowerCase()
  return /^(ru|uk|be)\b/.test(first) ? 'ru' : 'en'
}

export function translate(locale: Locale, key: MsgKey, params?: Record<string, string | number>) {
  let s = messages[locale][key] ?? en[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}
