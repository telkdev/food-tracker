export const messages: Record<Locale, Record<MsgKey, string>> = { en, ru, uk }

/** uk → uk, ru/be → ru, everything else → en. Accepts a navigator.language or an Accept-Language header. */
export function pickLocale(lang: string | null | undefined): Locale {
  const first = (lang || '').split(',')[0]!.trim().toLowerCase()
  if (/^uk\b/.test(first)) return 'uk'
  return /^(ru|be)\b/.test(first) ? 'ru' : 'en'
}

/** BCP 47 tag for Intl number/date formatting. */
export const intlTag: Record<Locale, string> = { ru: 'ru-RU', uk: 'uk-UA', en: 'en-GB' }

/** Locales with Slavic one/few/many plurals. */
export const slavicPlural = (l: Locale) => l === 'ru' || l === 'uk'

export function translate(locale: Locale, key: MsgKey, params?: Record<string, string | number>) {
  let s = messages[locale][key] ?? en[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}
